#!/usr/bin/env bash
# timeshift-setup.sh — deja Timeshift preconfigurado. Se llama desde porphyx-setup.sh (como root).
# Detecta si / es btrfs (modo BTRFS) o no (modo RSYNC). Nunca sobrescribe una config existente.
set -Eeuo pipefail
trap 'echo "ERROR: linea $LINENO: $BASH_COMMAND" >&2' ERR
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
TEMPLATE="$REPO/config/timeshift/timeshift.json.in"
DEST=/etc/timeshift/timeshift.json

[ "$(id -u)" -eq 0 ] || { echo "ABORT: correr con sudo" >&2; exit 1; }
command -v timeshift >/dev/null 2>&1 || { echo "ABORT: falta timeshift (official-packages.txt)" >&2; exit 1; }
[ -f "$TEMPLATE" ] || { echo "ABORT: falta $TEMPLATE" >&2; exit 1; }

ROOT_FS="$(findmnt -no FSTYPE /)"
ROOT_UUID="$(findmnt -no UUID /)"
[ -n "$ROOT_UUID" ] || { echo "ABORT: no pude leer el UUID de /" >&2; exit 1; }
if [ "$ROOT_FS" = btrfs ]; then BTRFS=true; else BTRFS=false; fi

install -d -m 755 /etc/timeshift
if [ -f "$DEST" ] && grep -q '"schedule_[a-z]*" : "true"' "$DEST"; then
  echo "= $DEST ya tiene horarios activos, no lo toco"
else
  if [ -f "$DEST" ]; then
    cp -a "$DEST" "$DEST.bak.$(date +%s)"
    echo "= config por defecto de timeshift respaldada en $DEST.bak.*"
  fi
  sed -e "s/@UUID@/$ROOT_UUID/" -e "s/@BTRFS@/$BTRFS/" "$TEMPLATE" > "$DEST"
  python3 -m json.tool "$DEST" >/dev/null || { rm -f "$DEST"; echo "ABORT: json invalido" >&2; exit 1; }
  chmod 644 "$DEST"
  echo "+ $DEST (fs=$ROOT_FS, btrfs_mode=$BTRFS)"
fi

# Timeshift programa con cron: cronie activo + entradas en /etc/cron.d (la GUI las crea al guardar; aqui las dejamos listas)
systemctl enable --now cronie.service >/dev/null && echo "+ cronie.service"
cat > /etc/cron.d/timeshift-hourly <<'CRON'
# Autogenerated by porphyx: revisa cada hora si toca snapshot diario/semanal segun timeshift.json
PATH=/sbin:/bin:/usr/sbin:/usr/bin
0 * * * * root timeshift --check --scripted
CRON
if grep -q '"schedule_boot" : "true"' "$DEST"; then
  cat > /etc/cron.d/timeshift-boot <<'CRON'
# Autogenerated by porphyx: snapshot de arranque
PATH=/sbin:/bin:/usr/sbin:/usr/bin
@reboot root sleep 10m && timeshift --create --scripted --tags B
CRON
else
  rm -f /etc/cron.d/timeshift-boot
fi
chmod 644 /etc/cron.d/timeshift-hourly /etc/cron.d/timeshift-boot 2>/dev/null || true
echo "+ /etc/cron.d/timeshift-*"
echo "✓ timeshift listo (los horarios los decide timeshift.json)"
